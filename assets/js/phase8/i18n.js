  let language = "zh";

  function t(key, values = {}) {
    const template = dictionaries[language]?.[key]
      ?? dictionaries.zh[key]
      ?? key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  }

  function setLanguage(next) {
    if (!Object.hasOwn(dictionaries, next)) {
      throw new Error(`Unsupported language: ${next}`);
    }
    language = next;
  }

  function tabletopScopeLabel(scope, format) {
    const suffix = {
      day1: "day1",
      day2: "day2",
      all_constructed: "all_constructed",
    }[scope];
    return suffix
      ? t(`tabletop.scope.${suffix}`, { format: t(`format.${format}`) })
      : scope;
  }

  root.P8I18n = Object.freeze({
    language: () => language,
    setLanguage,
    tabletopScopeLabel,
    t,
    translationKeys: languageId => Object.keys(dictionaries[languageId] || {}),
  });
