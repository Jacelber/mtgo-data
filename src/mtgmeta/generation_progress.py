"""Checkpoints for the existing finite publication producer sequence."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from time import perf_counter

from .resource_progress import digest, save


def files(root: Path, patterns):
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for pattern in patterns for p in sorted(root.glob(pattern))
            if p.is_file() and "__pycache__" not in p.parts}


# Existing shared classification/input machinery. Per-producer files are added
# by the caller; Landing rendering is deliberately not a statistics dependency.
COMMON = ["src/mtgmeta/" + name + ".py" for name in (
    "classifier", "rules", "legacy_rules", "config", "consumer", "public_contract",
    "classifier_features", "deck", "reports", "card_names", "mtgo/__init__",
    "mtgo/classification", "mtgo/normalize")]
COMMON += ["src/mtgmeta/data/*.json", "requirements.txt"]


def implementation(root, patterns):
    # The selected input checkout and the executing checkout can differ during
    # isolated repair. Retain both; never label old source as the executed code.
    executing = Path(__file__).resolve().parents[2]
    return {"selected": files(root, patterns), "executing": files(executing, patterns)}


class GenerationProgress:
    def __init__(self, path: Path, identity: dict):
        self.path = path
        self.state = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {
            "identity": identity, "steps": {}, "failure": None}
        if self.state["identity"] != identity:
            raise ValueError(f"Progress belongs to another task: {path}")
        self.reused = []
        self.executed = []

    def run(self, key, basis, root, outputs, produce, *, retain_result=False):
        signature = digest(basis)
        previous = self.state["steps"].get(key, {})
        current = files(root, outputs)
        if (previous.get("basis") == signature and previous.get("generated")
                and previous.get("outputs") == current):
            self.reused.append(key)
            return previous.get("result")
        started = perf_counter()
        self.state["failure"] = key
        save(self.path, self.state)
        try:
            result = produce()
            if retain_result:
                json.dumps(result)  # Only explicit data results may be checkpointed.
            snapshot = files(root, outputs)
            # The final publication validators remain mandatory. These hashes
            # establish generated bytes, not business acceptance or validation.
            self.state["steps"][key] = {"basis": signature, "generated": True,
                "basis_references": basis,
                "validated": False, "outputs": snapshot,
                "seconds": round(perf_counter() - started, 4),
                "executions": previous.get("executions", 0) + 1}
            if retain_result:
                self.state["steps"][key]["result"] = result
            self.state["failure"] = None
            save(self.path, self.state)
            self.executed.append(key)
            return result
        except BaseException as error:
            self.state["error"] = {"step": key, "type": type(error).__name__, "detail": str(error)}
            save(self.path, self.state)
            raise

    def validated(self):
        for step in self.state["steps"].values():
            step["validated"] = True
        self.state.pop("error", None)
        save(self.path, self.state)
